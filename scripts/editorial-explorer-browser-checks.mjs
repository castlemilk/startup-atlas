import assert from 'node:assert/strict';
import { indexCompanies } from '../web/atlas-exploration.js';

export async function checkEditorialExplorer({command,evaluate,navigate,until,click,press,screenshot,assertNoOverflow,graph}) {
  const company=indexCompanies(graph).get('startup:canva');
  assert.ok(company.country && company.city,'Canva needs sourced HQ for the continuity check');
  const trigger='.exploration-country-trigger';
  const popup='ui-popover-content.exploration-popover';
  const checkbox=code=>`.exploration-country-options [data-hq="${code}"] ui-checkbox`;
  const value=key=>evaluate(`new URLSearchParams(location.search).get(${JSON.stringify(key)})`);
  const countries=()=>evaluate("new URLSearchParams(location.search).getAll('hq')");
  const setSelect=(id,value)=>evaluate(`(()=>{const select=document.getElementById(${JSON.stringify(id)});select.value=${JSON.stringify(value)};select.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const directoryReady="document.querySelector('#results-list')?.getAttribute('aria-busy')==='false'&&!!document.querySelector('.exploration-country-trigger')&&document.body.dataset.atlasSdk==='ready'";
  const inspection='[data-inspect-entity="startup:canva"]';

  await command('Emulation.setDeviceMetricsOverride',{width:1440,height:1050,deviceScaleFactor:1,mobile:false});
  await navigate('/?type=startup#directory',directoryReady);
  await evaluate(`document.querySelector('${trigger}').focus()`);
  await press('Enter','Enter',13);
  await until(()=>evaluate(`document.querySelector('${popup}').getAttribute('data-open')!==null && !!document.querySelector('${checkbox(company.country)}')`),'Enter did not open the headquarters filter');
  const before=await evaluate("document.querySelector('.exploration-result-count').textContent");
  await click(checkbox(company.country));
  assert.deepEqual(await countries(),[],'Checkbox changes belong to the draft');
  assert.equal(await evaluate("document.querySelector('.exploration-result-count').textContent"),before);
  await press('Escape','Escape',27);
  await until(()=>evaluate(`document.activeElement===document.querySelector('${trigger}')`),'Escape did not restore focus');
  await click(trigger);
  await until(()=>evaluate(`document.querySelector('${checkbox(company.country)}')?.checked===false`),'Dismissal did not discard the draft');
  await click(checkbox(company.country));
  await click(checkbox('unknown'));
  await click('.exploration-apply');
  assert.deepEqual(await countries(),[company.country,'unknown']);

  await click('#search');
  await command('Input.insertText',{text:'Canva'});
  await until(()=>evaluate("new URLSearchParams(location.search).get('q')==='Canva' && !!document.querySelector('[data-inspect-entity=\"startup:canva\"]')"),'Company query did not retain Canva');
  await setSelect('atlas-drill',company.country);
  await setSelect('atlas-drill',company.city);
  assert.equal(await value('city'),company.city);
  await click(inspection);
  assert.equal(await value('selected'),'startup:canva');
  await click('.directory-company-row [data-atlas-compare="startup:canva"]');
  await until(()=>evaluate("document.querySelector('[data-atlas-panel=compare]').textContent==='Compare (1)'"),'Comparison was not added');
  await click('[data-atlas-view=treemap]');
  await until(()=>evaluate("document.querySelector('#treemap-workspace')?.getAttribute('aria-busy')==='false'&&document.querySelector('#treemap-detail h2')?.textContent==='Canva'"),'Treemap did not retain the inspected company');
  assert.equal(await value('q'),'Canva');
  assert.equal(await value('type'),'startup','Treemap should retain the directory type for the return route');
  assert.equal(await value('city'),company.city);
  assert.deepEqual(await countries(),[company.country,'unknown']);
  await screenshot('atlas-editorial-treemap-scope.png');

  await click('[data-atlas-view=graph]');
  await until(()=>evaluate("document.querySelector('#graph-detail h2')?.textContent==='Canva'&&!!document.querySelector('#graph-exploration .exploration-country-trigger')"),'Graph did not retain the inspected company');
  assert.equal(await value('city'),company.city);
  assert.deepEqual(await countries(),[company.country,'unknown']);
  assert.ok(await evaluate("!!document.querySelector('[data-node^=\"person:\"][data-context=true]')"),'Related people should remain available as graph context');
  await click(trigger);
  await click(checkbox(company.country));
  await click('.exploration-apply');
  await until(()=>evaluate("document.querySelector('.detail-selection-note')?.textContent==='Outside current results'"),'Filtered-out graph selection did not stay in the inspector');
  assert.equal(await value('selected'),'startup:canva');
  assert.match(await evaluate("document.querySelector('#graph-count').textContent"),/^0 companies in scope/);
  await click('[data-clear-facets]');
  assert.deepEqual(await countries(),[]);
  assert.equal(await value('city'),company.city,'Clear filters keeps the drill path');
  assert.equal(await value('selected'),'startup:canva');
  await click('[data-drill-parent=all]');
  assert.equal(await value('city'),null);
  assert.equal(await value('q'),'Canva','Returning to all ecosystems keeps search');
  assert.equal(await evaluate('document.activeElement.id'),'atlas-drill-trigger','Breadcrumb focus should reach the visible location selector');

  await click('[data-atlas-panel=compare]');
  await until(()=>evaluate("document.querySelector('.atlas-workspace-panel')?.checkVisibility()&&document.querySelector('.atlas-workspace-list dl')?.textContent.includes('Sydney')"),'Comparison did not show recorded company facts');
  assert.match(await evaluate("document.querySelector('.atlas-workspace-list a').textContent"),/Canva/);
  await press('Escape','Escape',27);
  await until(()=>evaluate("document.activeElement?.dataset.atlasPanel==='compare'"),'Workspace dismissal did not return focus');
  await click('#graph-zoom-in');
  const box=await evaluate("document.querySelector('#graph-canvas').getAttribute('viewBox')");
  const sourceRoute=await evaluate('location.pathname+location.search+location.hash');
  await click('#graph-detail [data-atlas-profile-link]');
  await until(()=>evaluate("document.querySelector('#entity-profile h1')?.textContent==='Canva'&&!!document.querySelector('[data-atlas-notes] textarea')"),'Canva profile did not load the workspace');
  assert.equal(await evaluate("new URL(document.querySelector('.entity-actions [data-atlas-profile-graph]').href).searchParams.get('q')"),'Canva');
  assert.equal(await evaluate("new URL(document.querySelector('.entity-actions [data-atlas-profile-graph]').href).searchParams.get('type')"),'startup');
  await click('[data-atlas-save-company="startup:canva"]');
  await until(()=>evaluate("document.querySelector('[data-atlas-panel=saved]').textContent==='Saved (1)'"),'Saving the company did not update the workspace');
  await click('[data-atlas-notes] textarea');
  await command('Input.insertText',{text:'Review the original announcement.'});
  await click('[data-atlas-notes] button[type=submit]');
  await until(()=>evaluate("document.querySelector('[data-atlas-notes] [role=status]').textContent==='Note saved'"),'Note did not acknowledge successful storage');
  assert.doesNotMatch(await evaluate('location.href'),/original announcement/);
  await click('[data-atlas-back]');
  await until(()=>evaluate("document.querySelector('#graph-detail h2')?.textContent==='Canva'"),'Profile return did not restore graph inspection');
  assert.equal(await evaluate('location.pathname+location.search+location.hash'),sourceRoute);
  assert.equal(await evaluate("document.querySelector('#graph-canvas').getAttribute('viewBox')"),box,'Profile return restores the graph camera');
  await click('[data-atlas-panel=saved]');
  await until(()=>evaluate("document.querySelector('.atlas-workspace-panel')?.checkVisibility()&&!!document.querySelector('.atlas-workspace-list a')"),'Saved companies did not survive navigation');
  await click('.atlas-workspace-list a');
  await until(()=>evaluate("document.querySelector('[data-atlas-notes] textarea')?.value==='Review the original announcement.'"),'Saved note did not survive navigation');

  await command('Emulation.setDeviceMetricsOverride',{width:320,height:760,deviceScaleFactor:1,mobile:true});
  await navigate('/?type=startup#directory',directoryReady);
  await click(trigger);
  await until(()=>evaluate(`document.querySelector('${popup}')?.checkVisibility()&&document.querySelector('${popup}')?.dataset.presentation==='sheet'&&!!document.querySelector('${checkbox(company.country)}')`),'Narrow headquarters control did not open as a sheet');
  await assertNoOverflow('320px headquarters options');
  await screenshot('atlas-editorial-mobile-filter.png');
  await click('[data-draft-cancel]');
  assert.deepEqual(await countries(),[]);
}
