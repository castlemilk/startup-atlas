#!/usr/bin/env python3
"""Build synthetic parity evidence with the real offline collection/storage code.

The collection observation and reviewed inputs are separate fixture sections.
Nothing promotes an observation into a reviewed record. Every generated byte is
written under an explicitly selected, initially empty directory outside the repo.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import sys
import types
from unittest.mock import patch
from urllib.parse import urlsplit

# Loading the production modules must not write caches beside their source.
sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[2]
FIXTURE_PATH = Path(__file__).with_name('fixtures.json')


def load_module(name, relative_path):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def write_json(path, value):
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + '\n',
        encoding='utf-8',
    )


class OfflineTransport:
    """Return one fixture response; unexpected requests fail without a network."""

    def __init__(self, collection):
        self.collection = collection
        self.seed = collection['registry']['sources'][0]['url']
        self.calls = []

    def request(self, url, allowed_host=None, **kwargs):
        if url != self.seed or allowed_host != urlsplit(self.seed).hostname:
            raise AssertionError(f'Unexpected offline request: {url!r}')
        self.calls.append(url)
        if len(self.calls) != 1:
            raise AssertionError('The fixture permits exactly one request')
        return (
            200,
            {'Content-Type': 'text/html'},
            self.collection['html'].encode('utf-8'),
            self.collection['final_url'],
        )


def build_fixture(output):
    output = Path(output).resolve()
    if output == ROOT or ROOT in output.parents:
        raise ValueError('The fixture output directory must be outside the repository')
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise ValueError('The fixture output directory must be new or empty')

    fixture = json.loads(FIXTURE_PATH.read_text(encoding='utf-8'))
    if fixture['fixture_version'] != 1:
        raise ValueError('Unsupported fixture version')
    crawl = load_module('atlas_canonical_parity_crawl', 'scripts/crawl.py')
    graph_builder = load_module('atlas_canonical_parity_graph', 'scripts/make-graph.py')
    database_builder = load_module('atlas_canonical_parity_db', 'scripts/build-graph-db.py')

    transport = OfflineTransport(fixture['collection'])
    args = types.SimpleNamespace(
        only=[], approved=None, limit=0, follow=0, partners_only=False,
    )
    with patch.object(crawl, 'utc_now', return_value=fixture['checked_at']):
        collection = crawl.crawl_program_directories(
            fixture['collection']['registry'], args, transport,
        )
    if transport.calls != [transport.seed]:
        raise AssertionError('The fixture collection did not make its one expected request')

    # These inputs are explicitly authored synthetic reviewed records, not a
    # conversion of the unreviewed `collection` result above.
    inputs = fixture['inputs']
    graph = graph_builder.build_graph(
        inputs['profiles'], inputs['leads'], inputs['reviewed'],
        inputs['catalogue'], inputs['research'],
    )
    graph['source_revision'] = fixture['source_revision']

    documents = {
        'catalogue.json': inputs['catalogue'],
        'graph.json': graph,
        'land.geojson': {'type': 'FeatureCollection', 'features': []},
        'map-locations.json': [],
        'opportunities-added.json': {'version': 1, 'entries': []},
        'partner-leads.json': inputs['leads'],
        'partner-logo-seeds.csv': 'partner,qid,official_website,approved,description,asset_hosts\n',
        'partner-profiles.json': inputs['profiles'],
        'partner-sources.json': {'sources': []},
        'partners-reviewed.json': inputs['reviewed'],
        'program-sources.json': fixture['collection']['registry'],
        'startup-news-sources.json': {'sources': []},
        'startup-research.json': inputs['research'],
        'treemap-evidence.json': {'version': 1, 'technology': {}, 'market_caps': []},
    }
    if set(documents) != set(database_builder.PUBLIC_DATA_FILES):
        raise AssertionError('Review synthetic fixtures when the public input allowlist changes')

    output.mkdir(parents=True, exist_ok=True)
    public_inputs = output / 'public-inputs'
    public_inputs.mkdir()
    write_json(output / 'collection.json', collection)
    write_json(output / 'graph.json', graph)
    for name, value in documents.items():
        if isinstance(value, str):
            (public_inputs / name).write_text(value, encoding='utf-8')
        else:
            write_json(public_inputs / name, value)

    # Supplying mappings prevents read_mappings() from importing real repository
    # logos/relationships or starting its Node export subprocess.
    database_builder.build(
        output / 'graph.json', output / 'atlas.sqlite', public_inputs,
        mappings={'logos': [], 'relationships': {}},
    )
    return {
        'fixture_version': fixture['fixture_version'],
        'source_revision': graph['source_revision'],
        'entities': len(graph['entities']),
        'observations': len(collection['candidates']),
        'public_documents': len(documents),
        'output': str(output),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(build_fixture(args.out), sort_keys=True))


if __name__ == '__main__':
    main()
