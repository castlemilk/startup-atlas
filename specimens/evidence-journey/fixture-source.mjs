// This is a UI fixture of the existing published-envelope shape, not a second
// graph generator or proof that source records and a published build agree.
function publishedEnvelope(record, revision, head) {
  return {
    revision,
    mainRevision: head,
    indexStatus: revision === head ? 'current' : 'pending_publication',
    startup: {
      id: targetId,
      kind: 'startup',
      name: record.name,
      summary: record.description,
      website: record.website,
      source: record.source,
      profile_facts: structuredClone(record.profile_facts),
      socials: [],
    },
    relationships: [],
    related_entities: [],
    funding_rounds: [],
    articles: [],
  };
}

